import 'package:flutter/widgets.dart';

/// ความกว้างอ้างอิงจากดีไซน์ (Figma) — ทุกค่าจะถูกคูณด้วย scale factor
/// ที่คำนวณจาก "ความกว้างจอจริง / ค่านี้"
///
/// ที่ความกว้าง 375 จะได้ scale = 1.0 พอดี จึงคงหน้าตาดีไซน์เดิมไว้
const double kDesignWidth = 375.0;

/// ตัวช่วยปรับขนาดทุกอย่าง (ฟอนต์ ระยะห่าง ไอคอน ปุ่ม ฯลฯ) ให้ย่อ/ขยาย
/// ตามขนาดหน้าจอแบบอัตโนมัติ
///
/// วิธีใช้: `context.rs(16)` แทนการเขียนค่าคงที่ `16`
extension ResponsiveSize on BuildContext {
  /// ตัวคูณสเกลเทียบความกว้างจอจริงกับความกว้างดีไซน์
  ///
  /// จำกัดช่วงไว้ไม่ให้เล็กหรือใหญ่เกินไป:
  /// - จอเล็ก (เช่น 320px) จะย่อลงเหลือ ~0.85 เท่า
  /// - จอใหญ่/แท็บเล็ต จะขยายได้สูงสุด 1.15 เท่า
  double get scale =>
      (MediaQuery.sizeOf(this).width / kDesignWidth).clamp(0.80, 1.15);

  /// คืนค่าที่ปรับสเกลตามหน้าจอแล้ว
  double rs(double value) => value * scale;
}
